/*
题目：蛋仔滚动

给定一个 m 行 n 列的地图，蛋仔从起点 (sr, sc) 出发，需要到达终点 (er, ec)。

蛋仔每次可以选择上、下、左、右之一开始滚动。一旦开始滚动，在遇到阻挡前无法主动停下。地图外侧视为额外包裹一圈障碍物。

地图中有三类特殊格子：
  # 障碍物，不能进入；
  / 斜挡板；
  \\ 反斜挡板。
题目保证起点和终点所在格子均不是特殊格子，特殊格子坐标互不重复。

挡板占据一格，进入挡板格后立即按挡板类型改变方向并继续滚动。

/ 型挡板：从左侧进入→向上，从右侧进入→向下，从上方进入→向左，从下方进入→向右。
\\ 型挡板：从左侧进入→向下，从右侧进入→向上，从上方进入→向右，从下方进入→向左。

（“从左侧进入”指从挡板左侧那一格滚入挡板，即当前运动方向为向右。）

一次「滚动」：从某个静止位置出发，选一个方向，直到再次停下为止；途中多次变向仍只算 1 次滚动。

若即将进入挡板格，但按规则得到的出口方向的下一格是 # 或另一块挡板，则该挡板不可进入，蛋仔停在进入挡板前的那一格。

只要某次滚动过程中经过终点格即视为成功，不要求恰好停在终点。

若在挡板间无限反弹，但过程中曾经过终点，仍视为可达。

求最少滚动次数；无法到达输出 -1。

输入：
  第一行 m, n（1 < m, n < 100）。
  第二行 k（0 < k < 10000）。
  接下来 k 行：r, c, ch（1-based，ch 为 #、/ 或 \\）。
  下一行 sr sc（起点，1-based）。
  最后一行 er ec（终点，1-based）。

输出：最少滚动次数，或 -1。

样例：
  3 5
  3
  1 3 #
  1 5 \\
  2 5 /
  2 1
  2 3
  输出：1
*/

