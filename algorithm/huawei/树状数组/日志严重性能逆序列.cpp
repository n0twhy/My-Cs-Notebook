/*
题目：日志严重性能逆序列

题目内容
在一段按时间顺序记录的日志中，给定每次请求的实时率数组 record。
实时率 RTF 定义为：合成耗时 / 目标文本音频时长。RTF 越高表示性能越差。

为便于处理，record 中存的是放大 100 倍后的整数值（正常场景 RTF < 1）。

若存在下标对 (i,j) 满足：
0 <= i < j < record.length 且 record[i] > record[j]，
则称为一个“性能逆序对”。

若进一步满足：
record[i] - record[j] > threshold，
则称为一个“严重性能逆序对”。

请统计并返回严重性能逆序对的总数。

输入描述
每组数据共三行：
第一行：阈值 threshold
第二行：日志数量 n
第三行：日志数组 record（可重复）

输入范围：
0 < record.length <= 100000
0 < record[i] <= 50000

输出描述
输出一个整数，表示严重性能逆序对的总数。

样例1
输入
2
5
9 7 5 4 6

输出
4

说明
record=[9,7,5,4,6], threshold=2。
严重性能逆序对有：
(9,5)、(9,4)、(9,6)、(7,4)。

样例2
输入
3
2
5 1

输出
1

说明
record=[5,1], threshold=3。
严重性能逆序对为 (5,1)。

样例3
输入
3
2
1 5

输出
0

说明
不存在满足条件的严重性能逆序对。
*/
