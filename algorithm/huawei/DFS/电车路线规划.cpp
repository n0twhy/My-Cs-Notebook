/*
题目：电车路线规划

题目内容
为了方便城市居民有序流动，城市 A 开通了一系列有轨电车路线，每列电车会沿固定的路线循环行驶，电车票价实行一票制，不论乘坐多少站，均按固定价格收费，循环坐车时不重复收费。请计算从出发点到目的地，乘坐电车的最低费用。

输入描述
第 1 行：M X Y Z，空格分隔。其中：
- M：电车线路总数量；
- X：起点编号；
- Y：终点编号；
- Z：身上的金钱数。

约束：1 <= M <= 50；0 <= X, Y <= 500；X != Y；1 <= Z <= 500。

第 2 行到第 M+1 行：每条线路一行，格式为：
price n station1 station2 station3 ... stationn

其中：
- price：本条线路票价；
- n：本条线路经过的站点数量；
- station1 ... stationn：本条线路经过的站点编号（按行驶顺序）。

约束：1 <= n <= 10；0 <= 各 station <= 500；1 <= price <= 10。
站点编号可能较大或与 n 无直接关系（题面说明 station 可能大于 n）。

输出描述
输出需要花费的金钱数。若无法到达或身上的钱不够，输出 -1。

样例1
输入：
5 15 12 4
2 2 7 12
3 3 4 5 15
4 1 6
3 2 15 7
1 3 12 13 7

输出：
4

说明：
共 5 条线路，从 15 到 12。可选路线例如：
a) 线路 4（15->7），在 7 换乘线路 1（7->12），花费 3+2=5；
b) 线路 4（15->7），在 7 换乘线路 5（经 7->3->12->13），花费 3+1=4。
第二种花费更小，为 4。

样例2
输入：
2 1 6 5
2 3 1 2 7
3 3 3 6 7

输出：
5

说明：
线路 1：票价 2，站点 [1,2,7]；
线路 2：票价 3，站点 [3,6,7]。
最优：在 1 乘线路 1 到 7，再换乘线路 2 到 6，共 2+3=5，不超过 5，输出 5。
*/

